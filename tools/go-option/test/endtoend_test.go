// This file contains a test that generates options of each package in testdata by
// its //go:generate directives, then compiles and runs it. A main package panics
// if the generated options are incorrect.

func TestEndToEnd(t *testing.T) {
	dir, gooptions := buildOptions(t)
	defer os.RemoveAll(dir)
	// Read the testdata directory.
	walkDir(dir, gooptions, "testdata", t)
}

// walkDir generates options of each package in testdata by its //go:generate directives,
// then runs the package if it is main, or builds it otherwise.
func walkDir(dir, gooptions, dirname string, t *testing.T) {
	files, err := ioutil.ReadDir(dirname)
	if err != nil {
		t.Fatalf("read dir[%s] failed %s", dirname, err)
		return
	}
	var sources []string
	for _, file := range files {
		name := file.Name()
		if file.IsDir() {
			walkDir(dir, gooptions, filepath.Join(dirname, name), t)
			continue
		}
		if !file.Mode().IsRegular() {
			continue
		}
		if !strings.HasSuffix(name, ".go") {
			t.Errorf("%s is not a Go file", name)
			continue
		}
		if strings.HasPrefix(name, ".") {
			// This file is ignored by the build tool since it's name starts with '.'.
			continue
		}
		if generated, err := isGenerated(filepath.Join(dirname, name)); err != nil {
			t.Fatal(err)
		} else if generated {
			// This file is generated by go-option, and generated again below.
			continue
		}
		if name == "cgo.go" && !build.Default.CgoEnabled {
			t.Logf("cgo is not enabled for %s", name)
			continue
		}
		sources = append(sources, filepath.Join(dirname, name))
	}
	if len(sources) > 0 {
		gooptionsCompileAndRun(t, dir, gooptions, sources)
	}
}

// buildOptions creates a temporary directory and installs go-option there.
func buildOptions(t *testing.T) (dir string, gooptions string) {
	t.Helper()
	dir, err := ioutil.TempDir("", "go-option")
	if err != nil {
		t.Fatal(err)
	}
	gooptions = filepath.Join(dir, "go-option.exe")
	err = run("go", "build", "-o", gooptions, "github.com/searKing/golang/tools/go-option")
	if err != nil {
		t.Fatalf("building go-option: %s", err)
	}
	return dir, gooptions
}

// gooptionsCompileAndRun copies the source files of a package into directory dir,
// runs go-option by their //go:generate directives, and runs the package if it is main,
// or builds it otherwise. A main package panics if the generated options are incorrect.
func gooptionsCompileAndRun(t *testing.T, dir, gooptions string, fileNames []string) {
	t.Helper()
	var sources []string
	var directives [][]string
	isMain := false
	for _, fileName := range fileNames {
		source := filepath.Join(dir, fileName)
		err := os.MkdirAll(filepath.Dir(source), os.ModePerm)
		if err != nil {
			t.Fatalf("mkdir temporary directory: %s", err)
		}
		err = copy(source, fileName)
		if err != nil {
			t.Fatalf("copying file to temporary directory: %s", err)
		}
		sources = append(sources, source)

		content, err := os.ReadFile(fileName)
		if err != nil {
			t.Fatal(err)
		}
		for _, line := range strings.Split(string(content), "\n") {
			if strings.TrimSpace(line) == "package main" {
				isMain = true
			}
			args, ok := strings.CutPrefix(line, "//go:generate go-option ")
			if !ok {
				continue
			}
			directive, err := splitArgs(args)
			if err != nil {
				t.Fatalf("parsing %q of %s: %s", line, fileName, err)
			}
			directives = append(directives, directive)
		}
	}
	if len(directives) == 0 {
		t.Fatalf("no //go:generate go-option directives in %s", filepath.Dir(fileNames[0]))
	}

	for _, directive := range directives {
		t.Logf("run: go-option %s %s\n", strings.Join(directive, " "), filepath.Dir(fileNames[0]))
		// Run gooptions on the files in the temporary directory, which outputs there.
		err := run(gooptions, append(directive, sources...)...)
		if err != nil {
			t.Fatal(err)
		}
	}

	generated, err := filepath.Glob(filepath.Join(filepath.Dir(sources[0]), "*.go"))
	if err != nil {
		t.Fatal(err)
	}
	if isMain {
		err = run("go", append([]string{"run"}, generated...)...)
	} else {
		err = run("go", append([]string{"build", "-o", os.DevNull}, generated...)...)
	}
	if err != nil {
		t.Fatal(err)
	}
}

// isGenerated reports whether the file is generated by go-option.
func isGenerated(fileName string) (bool, error) {
	content, err := os.ReadFile(fileName)
	if err != nil {
		return false, err
	}
	return bytes.HasPrefix(content, []byte(`// Code generated by "go-option `)), nil
}

// splitArgs splits arguments of a //go:generate directive by spaces, unquoting quoted ones.
func splitArgs(line string) ([]string, error) {
	var args []string
	for _, field := range strings.Fields(line) {
		if strings.HasPrefix(field, `"`) {
			arg, err := strconv.Unquote(field)
			if err != nil {
				return nil, err
			}
			field = arg
		}
		args = append(args, field)
	}
	return args, nil
}

// copy copies the from file to the to file.
func copy(to, from string) error {
	toFd, err := os.Create(to)
	if err != nil {
		return err
	}
	defer toFd.Close()
	fromFd, err := os.Open(from)
	if err != nil {
		return err
	}
	defer fromFd.Close()
	_, err = io.Copy(toFd, fromFd)
	return err
}

// run runs a single command and returns an error if it does not succeed.
// os/exec should have this function, to be honest.
func run(name string, arg ...string) error {
	return runInDir(".", name, arg...)
}

// runInDir runs a single command in directory dir and returns an error if
// it does not succeed.
func runInDir(dir, name string, arg ...string) error {
	cmd := exec.Command(name, arg...)
	cmd.Dir = dir
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	cmd.Env = append(os.Environ(), "GO111MODULE=auto")
	return cmd.Run()
}
