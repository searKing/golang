package main

import (
	"flag"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	gengo "google.golang.org/protobuf/cmd/protoc-gen-go/internal_gengo"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

//go:generate ./gen.sh

var update = flag.Bool("update", false, "update golden files of testdata/golden")

// protosFile is the descriptor set of examples/example.proto and testdata/proto/**/*.proto, generated by gen.sh.
const protosFile = "testdata/protos.binpb"

func TestGolden(t *testing.T) {
	// Version markers change with versions of protobuf and protoc, which golden files do not care about.
	gengo.GenerateVersionMarkers = false
	defer func() { gengo.GenerateVersionMarkers = true }()

	b, err := os.ReadFile(protosFile)
	if err != nil {
		t.Fatal(err)
	}
	var protos descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(b, &protos); err != nil {
		t.Fatal(err)
	}

	tests := []struct {
		name    string
		files   []string
		wantErr string
	}{
		{name: "example", files: []string{"example.proto"}},
		{name: "edge", files: []string{"edge/edge.proto"}},
		{name: "comment", files: []string{"comment/comment.proto"}},
		{name: "samename", files: []string{"samename/a/http.proto", "samename/b/http.proto"}},
		{name: "reserved_key", files: []string{"invalid/reserved_key.proto"},
			wantErr: `invalid.ReservedKey.name: field_tag: must not set struct tag "protobuf"`},
		{name: "comment_reserved_key", files: []string{"invalid/comment_reserved_key.proto"},
			wantErr: `invalid.CommentReservedKey.name: @gotags: must not set struct tag "protobuf_oneof"`},
		{name: "malformed", files: []string{"invalid/malformed.proto"},
			wantErr: `invalid.Malformed.name: field_tag: malformed struct tag "validate:\"required"`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			resp := run(t, &pluginpb.CodeGeneratorRequest{
				FileToGenerate: tt.files,
				Parameter:      proto.String("paths=source_relative"),
				ProtoFile:      protos.GetFile(),
			})
			if tt.wantErr != "" {
				if !strings.Contains(resp.GetError(), tt.wantErr) {
					t.Fatalf("error = %q, want containing %q", resp.GetError(), tt.wantErr)
				}
				return
			}
			if resp.GetError() != "" {
				t.Fatalf("error = %q", resp.GetError())
			}
			checkGolden(t, filepath.Join("testdata", "golden", tt.name), resp.GetFile())
		})
	}
}

// run runs the plugin with req, as protoc does.
func run(t *testing.T, req *pluginpb.CodeGeneratorRequest) *pluginpb.CodeGeneratorResponse {
	t.Helper()
	gen, err := protogen.Options{}.New(req)
	if err != nil {
		t.Fatal(err)
	}
	if err := generate(gen); err != nil {
		gen.Error(err)
	}
	return gen.Response()
}

// checkGolden compares files with golden files in dir, named by the files with the suffix .golden,
// or updates the golden files if -update is set.
func checkGolden(t *testing.T, dir string, files []*pluginpb.CodeGeneratorResponse_File) {
	t.Helper()
	if *update {
		if err := os.RemoveAll(dir); err != nil {
			t.Fatal(err)
		}
	}
	var got []string
	for _, f := range files {
		golden := filepath.Join(dir, f.GetName()+".golden")
		got = append(got, golden)
		if *update {
			if err := os.MkdirAll(filepath.Dir(golden), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(golden, []byte(f.GetContent()), 0o644); err != nil {
				t.Fatal(err)
			}
			continue
		}
		want, err := os.ReadFile(golden)
		if err != nil {
			t.Fatalf("%v, run 'go test -update' to create it", err)
		}
		if f.GetContent() != string(want) {
			t.Errorf("%s differs from %s, run 'go test -update' if it is expected:\n%s", f.GetName(), golden, f.GetContent())
		}
	}

	var want []string
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			want = append(want, path)
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	slices.Sort(got)
	if !slices.Equal(got, want) {
		t.Errorf("generated files %q, want %q", got, want)
	}
}
